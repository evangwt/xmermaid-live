export const MESSAGES: Readonly<Record<Locale, Readonly<Record<MessageKey, string>>>> = {
  'zh-CN': zhCN,
  en,
};

export interface Translator {
  locale: Locale;
  text(key: MessageKey, values?: MessageValues): string;
}

export function parseLocale(value: string | null | undefined): Locale | null {
  return value === 'zh-CN' || value === 'en' ? value : null;
}

export function resolveLocale(savedLocale: string | null | undefined, _browserLanguage?: string): Locale {
  return parseLocale(savedLocale) ?? 'en';
}

export function serializeLocale(locale: Locale): string {
  return locale;
}

export function createTranslator(locale: Locale): Translator {
  return {
    locale,
    text(key, values = {}) {
      return MESSAGES[locale][key].replace(/{{(\w+)}}/g, (_, name: string) => String(values[name] ?? `{{${name}}}`));
    },
  };
}
