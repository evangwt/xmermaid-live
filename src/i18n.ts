export const MESSAGES: Readonly<Record<Locale, Readonly<Record<MessageKey, string>>>> = {
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  en,
  ja,
  ko,
  es,
  fr,
  de,
  it,
  'pt-BR': ptBR,
  ru,
  ar,
};

export interface Translator {
  locale: Locale;
  text(key: MessageKey, values?: MessageValues): string;
}

export function parseLocale(value: string | null | undefined): Locale | null {
  return typeof value === 'string' && (SUPPORTED_LOCALES as readonly string[]).includes(value)
    ? value as Locale
    : null;
}

function resolveBrowserLocale(value: string): Locale | null {
  let browserLocale: Intl.Locale;
  try {
    browserLocale = new Intl.Locale(value.trim());
  } catch {
    return null;
  }

  const normalized = browserLocale.toString().toLowerCase();

  const exact = SUPPORTED_LOCALES.find(locale => locale.toLowerCase() === normalized);
  if (exact) return exact;

  const primary = browserLocale.language.toLowerCase();
  if (primary === 'zh') {
    const script = browserLocale.script?.toLowerCase();
    const region = browserLocale.region?.toLowerCase();
    const traditional = script === 'hant' || region === 'tw' || region === 'hk' || region === 'mo';
    return traditional ? 'zh-TW' : 'zh-CN';
  }
  if (primary === 'pt') return 'pt-BR';

  return parseLocale(primary);
}

export function resolveLocale(
  savedLocale: string | null | undefined,
  browserLanguages: readonly string[] | string = [],
  browserLanguage?: string,
): Locale {
  const saved = parseLocale(savedLocale);
  if (saved) return saved;

  const candidates = typeof browserLanguages === 'string'
    ? [browserLanguages, browserLanguage]
    : [...browserLanguages, browserLanguage];
  for (const candidate of candidates) {
    if (typeof candidate !== 'string') continue;
    const resolved = resolveBrowserLocale(candidate);
    if (resolved) return resolved;
  }
  return 'en';
}

export function serializeLocale(locale: Locale): string {
  return locale;
}

export function createTranslator(locale: Locale): Translator {
  return {
    locale,
    text(key, values = {}) {
      return MESSAGES[locale][key].replace(/{{(\w+)}}/g, (_, name: string) => String(values[name] ?? `{{${name}}}`));
    },
  };
}
